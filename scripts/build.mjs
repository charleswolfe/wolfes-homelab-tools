#!/usr/bin/env node
// Production build: copies site/ to <out>/site, writes sitemap.xml and
// robots.txt, pre-compresses text assets (brotli + gzip), generates the
// static-web-server header configs and computes the memory-cache budget.
//
//   node scripts/build.mjs --out dist --site-url https://tools.lan
//
// Uses only Node built-ins so it runs anywhere without npm install.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, extname, relative } from 'node:path';
import { brotliCompressSync, gzipSync, constants as zlib } from 'node:zlib';
import { tools } from '../site/assets/tools.js';
import { COMMON_HEADERS, HSTS_ON, HSTS_OFF, STRICT_CSP, STRICT_PAGES, DNS_CSP, DNS_PAGES, VIA_CSP, VIA_PATH, FAVICON_PATH, FAVICON_CORP } from './security.mjs';

const MiB = 1024 * 1024;
const CACHE_CAP = 50 * MiB;          // spec: cap the cache at 50 MB
const CACHE_RATIO = 1.0;             // spec: reserve 50–100% of asset size; use the top of the range
const SERVER_OVERHEAD = 16 * MiB;    // static-web-server + busybox; measured 9–11 MiB in use incl. page cache
const COMPRESSIBLE = new Set(['.html', '.js', '.mjs', '.css', '.svg', '.json', '.xml', '.txt', '.webmanifest', '.map']);
const NO_PRECOMPRESS = new Set(['sitemap.xml', 'robots.txt']); // may be rewritten at container start

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1]]);
  return acc;
}, []));
const OUT = args.out || 'dist';
const SITE_URL = (args['site-url'] || 'http://localhost:8080').replace(/\/+$/, '');
if (!/^https?:\/\/[^/\s]+$/.test(SITE_URL)) {
  console.error(`--site-url must look like https://host[:port] (got "${SITE_URL}")`);
  process.exit(1);
}

const ROOT = new URL('..', import.meta.url).pathname;
const siteOut = join(OUT, 'site');
const etcOut = join(OUT, 'etc');
rmSync(OUT, { recursive: true, force: true });
mkdirSync(etcOut, { recursive: true });
cpSync(join(ROOT, 'site'), siteOut, { recursive: true });

// ---------- sitemap + robots ----------

const today = new Date().toISOString().slice(0, 10);
const urls = ['/', ...tools.filter((t) => t.ready).map((t) => t.path)];
writeFileSync(join(siteOut, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${SITE_URL}${u}</loc><lastmod>${today}</lastmod><priority>${u === '/' ? '1.0' : '0.8'}</priority></url>`).join('\n')}
</urlset>
`);
writeFileSync(join(siteOut, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${SITE_URL}/sitemap.xml\n`);

// ---------- pre-compression ----------

const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

// VIA only works over HTTPS (WebHID), where every browser accepts brotli, so
// its ~3,400 definition files skip the gzip copy.
const BROTLI_ONLY = `${VIA_PATH}definitions/`;

let saved = 0;
for (const file of walk(siteOut)) {
  const rel = relative(siteOut, file);
  if (!COMPRESSIBLE.has(extname(file)) || NO_PRECOMPRESS.has(rel)) continue;
  const raw = readFileSync(file);
  if (raw.length < 512) continue;
  // Quality 11 is slow on thousands of small files; 9 is within ~5% of it.
  const quality = rel.startsWith(BROTLI_ONLY) ? 9 : 11;
  const br = brotliCompressSync(raw, { params: { [zlib.BROTLI_PARAM_QUALITY]: quality, [zlib.BROTLI_PARAM_SIZE_HINT]: raw.length } });
  // Only keep a variant if it's meaningfully smaller.
  if (br.length < raw.length * 0.95) { writeFileSync(file + '.br', br); saved += raw.length - br.length; }
  if (rel.startsWith(BROTLI_ONLY)) continue;
  const gz = gzipSync(raw, { level: 9 });
  if (gz.length < raw.length * 0.95) writeFileSync(file + '.gz', gz);
}

// ---------- header configs for static-web-server ----------

const tomlString = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const headerRule = (source, headers) => `[[advanced.headers]]
source = "${source}"
headers = { ${Object.entries(headers).map(([k, v]) => `${k} = ${tomlString(v)}`).join(', ')} }
`;
// [general] repeats a value the entrypoint also sets via env; without any
// general key static-web-server logs a warning on every start.
// Rules are applied in order and later ones override earlier ones for the
// same header; sources need a leading slash.
const toml = (headers) => `# Generated by scripts/build.mjs. Do not edit.
[general]
directory-listing = false

[advanced]

${headerRule('**', headers)}
${STRICT_PAGES.map((p) => headerRule(`/${p.replace(/index\.html$/, '')}**`, { 'Content-Security-Policy': `${STRICT_CSP}; frame-ancestors 'self'` })).join('\n')}
${DNS_PAGES.map((p) => headerRule(`/${p.replace(/index\.html$/, '')}**`, { 'Content-Security-Policy': `${DNS_CSP}; frame-ancestors 'self'` })).join('\n')}
${headerRule(`/${VIA_PATH}**`, { 'Content-Security-Policy': `${VIA_CSP}; frame-ancestors 'self'` })}
${headerRule(`/${FAVICON_PATH}`, { 'Cross-Origin-Resource-Policy': FAVICON_CORP })}`;
writeFileSync(join(etcOut, 'sws-http.toml'), toml(COMMON_HEADERS));
writeFileSync(join(etcOut, 'sws-https-hsts.toml'), toml({ ...COMMON_HEADERS, 'Strict-Transport-Security': HSTS_ON }));
writeFileSync(join(etcOut, 'sws-https.toml'), toml({ ...COMMON_HEADERS, 'Strict-Transport-Security': HSTS_OFF }));

// ---------- memory-cache budget ----------

const files = walk(siteOut);
const total = files.reduce((n, f) => n + statSync(f).size, 0);
const jsHtml = files.filter((f) => /\.(m?js|html)$/.test(f)).reduce((n, f) => n + statSync(f).size, 0);
const budget = Math.min(Math.ceil(total * CACHE_RATIO), CACHE_CAP);
const memLimitMiB = Math.ceil((SERVER_OVERHEAD + budget) / MiB / 8) * 8; // round up to 8 MiB steps

writeFileSync(join(etcOut, 'build.env'), [
  `BUILD_DATE=${today}`,
  `BUILD_SITE_URL=${SITE_URL}`,
  `ASSET_BYTES=${total}`,
  `JS_HTML_BYTES=${jsHtml}`,
  `CACHE_BUDGET_BYTES=${budget}`,
  `MEM_LIMIT_MIB=${memLimitMiB}`,
  '',
].join('\n'));

const fmt = (n) => (n >= MiB ? `${(n / MiB).toFixed(2)} MiB` : `${(n / 1024).toFixed(1)} KiB`);
console.log(`homelab-tools build
  pages in sitemap     ${urls.length} (${SITE_URL})
  files served         ${files.length}
  JS + HTML            ${fmt(jsHtml)}
  all served files     ${fmt(total)} (incl. .br/.gz; brotli saved ${fmt(saved)})
  memory-cache budget  ${fmt(budget)} (${Math.round(CACHE_RATIO * 100)}% of assets, capped at ${fmt(CACHE_CAP)})
  recommended limit    ${memLimitMiB}m  (server baseline + cache budget)`);
